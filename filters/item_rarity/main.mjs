// Generates data/scripts/core/itemRarity.ts from the item JSON files, because the Script API
// can't read an item's rarity or name color. Runs before esbuild in every rgl profile.
// Inside rgl the packs sit at ./BP, run by hand from the project root they sit at ./packs/BP:
//   node filters/item_rarity/main.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ITEMS_DIR = existsSync("./BP/items") ? "./BP/items" : "./packs/BP/items";
const OUT_FILE = "./data/scripts/core/itemRarity.ts";

// Vanilla items have no JSON in the pack, so their rarity is listed here, taken from the
// Bedrock column of minecraft.wiki/w/Rarity. Everything not listed is common.
const SHERDS = ["angler", "archer", "arms_up", "blade", "brewer", "burn", "danger", "explorer", "flow", "friend",
    "guster", "heart", "heartbreak", "howl", "miner", "mourner", "plenty", "prize", "scrape", "sheaf", "shelter",
    "skull", "snort"].map(name => `${name}_pottery_sherd`);
const trims = names => names.map(name => `${name}_armor_trim_smithing_template`);
const discs = names => names.map(name => `music_disc_${name}`);

const VANILLA = {
    uncommon: [
        "creeper_banner_pattern", "piglin_banner_pattern", "book", "sniffer_egg", "chainmail_helmet",
        "chainmail_chestplate", "chainmail_leggings", "chainmail_boots", "recovery_compass", "disc_fragment_5",
        "nautilus_shell", "echo_shard", "goat_horn", "ominous_bottle", "netherite_upgrade_smithing_template",
        "totem_of_undying", "experience_bottle", "conduit", "heart_of_the_sea", "dragon_breath", "player_head",
        "zombie_head", "creeper_head", "skeleton_skull", "piglin_head",
        ...SHERDS,
        ...trims(["sentry", "dune", "coast", "wild", "tide", "snout", "rib", "wayfinder", "shaper", "raiser", "host", "flow", "bolt"]),
        ...discs(["13", "cat", "blocks", "chirp", "far", "mall", "mellohi", "stal", "strad", "ward", "11", "wait", "5",
            "relic", "creator_music_box", "precipice", "tears", "lava_chicken"])
    ],
    rare: [
        "flow_banner_pattern", "guster_banner_pattern", "skull_banner_pattern", "mojang_banner_pattern",
        "enchanted_golden_apple", "trident", "nether_star", "wither_skeleton_skull", "beacon",
        ...trims(["ward", "eye", "vex", "spire"]),
        ...discs(["pigstep", "otherside", "creator"])
    ],
    epic: [
        "elytra", "dragon_head", "dragon_egg", "heavy_core", "mace",
        ...trims(["silence"])
    ]
};

function listJson(dir) {
    return readdirSync(dir, { recursive: true })
        .map(String)
        .filter(file => file.endsWith(".json"))
        .map(file => join(dir, file));
}

const rarity = [];
for (const file of listJson(ITEMS_DIR)) {
    let item;
    try {
        item = JSON.parse(readFileSync(file, "utf8"))["minecraft:item"];
    } catch (err) {
        console.warn(`[item_rarity] skipped ${file}: ${err.message}`);
        continue;
    }
    const id = item?.description?.identifier;
    const components = item?.components ?? {};
    if (!id) continue;

    // Legendary is Phantasm's own tier above epic, marked by a gold item name
    if (components["minecraft:hover_text_color"] === "gold") {
        rarity.push([id, "legendary"]);
        continue;
    }

    let value = components["minecraft:rarity"];
    if (typeof value === "object") value = value?.value;
    if (value && value !== "common") rarity.push([id, value]);
}
rarity.sort(([a], [b]) => a.localeCompare(b));
for (const [level, ids] of Object.entries(VANILLA)) {
    for (const id of ids) rarity.push([`minecraft:${id}`, level]);
}

const entries = list => list.map(([id, value]) => `    ["${id}", "${value}"],`).join("\n");

writeFileSync(OUT_FILE, `// GENERATED by filters/item_rarity/main.mjs on every rgl run, don't edit by hand.
// Change minecraft:rarity / minecraft:hover_text_color in the item JSON instead, or the
// vanilla list in the filter. A gold hover_text_color makes the item legendary.
import { ItemStack } from '@minecraft/server'

export type ItemRarity = "common" | "uncommon" | "rare" | "epic" | "legendary"

const RARITY = new Map<string, ItemRarity>([
${entries(rarity)}
])

const UPGRADE: Record<ItemRarity, ItemRarity> = { common: "rare", uncommon: "rare", rare: "epic", epic: "epic", legendary: "legendary" }

// Same rule as vanilla, enchanted common/uncommon items become rare and rare becomes epic.
// Enchanted books stay common on Bedrock.
export function getItemRarity(item: ItemStack): ItemRarity {
    const base = RARITY.get(item.typeId) ?? "common"
    if (base === "epic" || base === "legendary" || item.typeId === "minecraft:enchanted_book") return base
    const enchanted = (item.getComponent("minecraft:enchantable")?.getEnchantments().length ?? 0) > 0
    return enchanted ? UPGRADE[base] : base
}
`);
console.log(`[item_rarity] ${rarity.length} rarity entries`);
